package org.eclipse.cyclonedds.omg;

import java.lang.reflect.InvocationTargetException;
import java.util.Objects;
import org.omg.dds.core.ServiceEnvironment;
import org.omg.dds.type.TypeSupport;

final class CycloneTypeSupport<T> extends TypeSupport<T> {
    private final ServiceEnvironment env;
    private final Class<T> type;
    private final String registeredName;
    private final org.eclipse.cyclonedds.topic.TypeSupport<T> binding;
    final int builtinKind;
    private final org.eclipse.cyclonedds.topic.TypeSupport.Codec<T> builtinCodec;

    @SuppressWarnings("unchecked")
    CycloneTypeSupport(ServiceEnvironment env, int builtinKind) {
        this.env = env; this.builtinKind = builtinKind;
        type = (Class<T>)Discovery.TYPES.get(builtinKind-1);
        registeredName = "DDS::" + type.getSimpleName(); binding = null;
        builtinCodec = org.eclipse.cyclonedds.core.cdr.CdrCodecs.of((w, value) -> { throw Policies.unsupported("Serializing discovery snapshots as application data"); },
            r -> { throw Policies.unsupported("Decoding discovery data through an application codec"); });
    }

    @SuppressWarnings("unchecked")
    CycloneTypeSupport(ServiceEnvironment env, Class<T> type, String name) {
        this.env = env; this.type = Objects.requireNonNull(type);
        builtinKind = 0; builtinCodec = null;
        try {
            java.lang.reflect.Method factory;
            try { factory = type.getDeclaredMethod("$typeSupport$" + type.getSimpleName()); }
            catch (NoSuchMethodException oldGenerator) { factory = type.getDeclaredMethod("typeSupport"); }
            Object generated = factory.invoke(null);
            if (!(generated instanceof org.eclipse.cyclonedds.topic.TypeSupport<?>))
                throw new IllegalArgumentException("Missing generated Cyclone type support");
            binding = (org.eclipse.cyclonedds.topic.TypeSupport<T>) generated;
            registeredName = name == null ? binding.typeName() : name;
            if (registeredName.isBlank() || registeredName.indexOf('\0') >= 0)
                throw new IllegalArgumentException("Invalid registered type name");
            type.getConstructor();
        } catch (ReflectiveOperationException error) {
            throw new IllegalArgumentException("Type must be generated by idljava and have a default constructor", error);
        }
    }
    org.eclipse.cyclonedds.topic.TypeSupport<T> binding() {
        if (binding == null) throw Policies.unsupported("Using built-in discovery types as application topics");
        return binding;
    }
    org.eclipse.cyclonedds.topic.TypeSupport.Codec<T> codec() { return builtinKind == 0 ? binding.codec() : builtinCodec; }
    @SuppressWarnings("unchecked")
    public T newData() {
        if (builtinKind != 0) return (T)Discovery.empty(env, builtinKind);
        try { return type.getConstructor().newInstance(); }
        catch (InvocationTargetException error) { throw new IllegalStateException("Generated constructor failed", error.getCause()); }
        catch (ReflectiveOperationException error) { throw new IllegalStateException(error); }
    }
    public Class<T> getType() { return type; }
    public String getTypeName() { return registeredName; }
    public ServiceEnvironment getEnvironment() { return env; }
}
